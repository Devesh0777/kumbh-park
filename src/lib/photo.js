/**
 * Returns a high quality real photo URL for any spot ID, booking ID, or seed string.
 */
export function photoUri(seed, label = 'PARKING SPOT', index = 0) {
  if (!seed) return GENERAL_PHOTOS[0]

  const str = String(seed)

  // Direct spot ID match (e.g. 's1', 's2')
  if (SPOT_PHOTOS[str]) {
    const list = SPOT_PHOTOS[str]
    return list[index % list.length]
  }

  // Booking ID match (e.g. 'b1', 'b2')
  const spotKey = BOOKING_SPOT_MAP[str]
  if (spotKey && SPOT_PHOTOS[spotKey]) {
    const list = SPOT_PHOTOS[spotKey]
    return list[index % list.length]
  }

  // Seed containing spot ID and slide index (e.g. 's1-0', 's1-2')
  const parts = str.split('-')
  const spotId = parts[0]
  const subIndex = parts.length > 1 ? parseInt(parts[1], 10) : index

  if (SPOT_PHOTOS[spotId]) {
    const list = SPOT_PHOTOS[spotId]
    const chosenIndex = isNaN(subIndex) ? index : subIndex
    return list[chosenIndex % list.length]
  }

  // Fallback to deterministic curated photo from general list
  const h = hash(str)
  return GENERAL_PHOTOS[h % GENERAL_PHOTOS.length]
}
