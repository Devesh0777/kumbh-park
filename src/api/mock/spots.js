function nearestGhat(latlng) {
  let best = null
  for (const g of ghatPoints) {
    const km = haversineKm(latlng, g.latlng)
    if (!best || km < best.km) best = { ghat: g, km }
  }
  return best
}

function availabilityOf(spot) {
  if (spot.spotsLeft <= 0) return 'full'
  if (spot.spotsLeft / spot.capacity <= 0.34) return 'filling'
  return 'available'
}

export const spots = raw.map((spot) => {
  const { ghat, km } = nearestGhat(spot.latlng)
  const distanceM = Math.round(km * 1000)
  return {
    ...spot,
    photos: [],
    zone: zoneById(spot.zoneId),
    ghat: { name: ghat.name, distanceM },
    distanceM,
    walkM: Math.max(1, Math.round((km / 4.5) * 60)),
    availability: availabilityOf(spot),
    status: availabilityOf(spot),
  }
})

export const spotById = (id) => spots.find((s) => s.id === id)

